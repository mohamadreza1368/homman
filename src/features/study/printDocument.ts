/**
 * Evaluates whether any portions of the printout document contain AI-generated text.
 */
export function hasGeneratedText(doc: PrintDocument): boolean {
  const containsAssistantProse = (messages: PrintExchange[]) =>
    messages.some((item) => item.role === "assistant" && item.model !== null);

  const directAnswerHasModel = containsAssistantProse(doc.exchanges);
  const closingVerdictExists = doc.verdict !== null;
  const visitAssessmentExists = doc.visits.some(
    (visitItem) => visitItem.verdict !== null || containsAssistantProse(visitItem.exchanges),
  );

  return directAnswerHasModel || closingVerdictExists || visitAssessmentExists;
}

/**
 * Generates bilingual AI disclosure statements if the document includes model-produced text.
 */
export function aiNotice(doc: PrintDocument): string[] {
  if (!hasGeneratedText(doc)) return [];
  const activeLang = doc.language;
  if (activeLang === "auto") {
    return [
      ARTIFICIAL_INTELLIGENCE_DISCLOSURE.bg,
      ARTIFICIAL_INTELLIGENCE_DISCLOSURE.es,
      ARTIFICIAL_INTELLIGENCE_DISCLOSURE.en,
    ];
  }
  return activeLang === "en"
    ? [ARTIFICIAL_INTELLIGENCE_DISCLOSURE.en]
    : [ARTIFICIAL_INTELLIGENCE_DISCLOSURE[activeLang], ARTIFICIAL_INTELLIGENCE_DISCLOSURE.en];
}

/**
 * Infers primary document language from recent journal sessions, falling back to English.
 */
export function journalLanguage(sessionSummaries: SessionSummary[]): Language {
  let mostRecentEntry: SessionSummary | null = null;
  for (const item of sessionSummaries) {
    if (!mostRecentEntry || item.updated_at > mostRecentEntry.updated_at) {
      mostRecentEntry = item;
    }
  }
  return mostRecentEntry?.language ?? "en";
}

/**
 * Formats a chat dialogue session into an exportable/printable document.
 */
export function buildSessionDocument(
  detail: SessionDetail,
  labelFor: (organId: string) => string | null,
  producedAt: number = Date.now(),
): PrintDocument {
  const sessionData = detail.session;

  const metadataFacts: PrintFact[] = [
    { label: "Kind", value: SESSION_KIND_LABELS[sessionData.kind] },
    { label: "Level", value: AUDIENCE_PROFILE_LABELS[sessionData.profile] },
    { label: "Answered in", value: SPOKEN_LANGUAGE_LABELS[sessionData.language] },
  ];

  if (sessionData.kind === "case" && sessionData.score !== null) {
    metadataFacts.push({ label: "Score", value: `${sessionData.score} / 100` });
  }

  const sortedOrganNames = detail.structures
    .map(labelFor)
    .filter((title): title is string => title !== null)
    .sort((a, b) => a.localeCompare(b));

  const cleanMessageExchanges = detail.messages.map((msg) => ({
    role: msg.role,
    body: stripOrganRefs(msg.content),
    when: msg.created_at,
    model: msg.model,
  }));

  return {
    heading: sessionData.title,
    kind: "session",
    facts: metadataFacts,
    verdict: sessionData.verdict,
    structures: sortedOrganNames,
    notes: [],
    findings: null,
    recordUpdates: [],
    symptoms: [],
    visits: [],
    sealedAnswer: null,
    exchanges: cleanMessageExchanges,
    language: sessionData.language,
    createdAt: sessionData.created_at,
    updatedAt: sessionData.updated_at,
    producedAt,
  };
}

/**
 * Assembles personal study notes into a printable document structure.
 */
export function buildNotesDocument(
  notesList: StudyNote[],
  targetStructure: string | null,
  preferredLanguage: Language,
  producedAt: number = Date.now(),
): PrintDocument {
  const formattedNotes = notesList.map((entry) => ({
    when: entry.updated_at,
    structure: entry.organ_label,
    body: entry.body,
  }));

  return {
    heading: targetStructure ? `Notes on ${targetStructure}` : "My notes",
    kind: "notes",
    facts: [{ label: "Notes", value: String(notesList.length) }],
    verdict: null,
    structures: [],
    notes: formattedNotes,
    exchanges: [],
    findings: null,
    recordUpdates: [],
    symptoms: [],
    visits: [],
    sealedAnswer: null,
    language: preferredLanguage,
    createdAt: null,
    updatedAt: null,
    producedAt,
  };
}

/**
 * Compiles a complete simulated clinical case record with historical visits, marked complaints, and findings.
 */
export function buildCaseDocument(
  caseDigest: CaseDigest,
  sessionDetailsMap: ReadonlyMap<string, SessionDetail>,
  labelFor: (organId: string) => string | null,
  producedAt: number = Date.now(),
): PrintDocument {
  const caseData = caseDigest.case;

  const headerFacts: PrintFact[] = [
    { label: "Record", value: "Simulated case — no real patient" },
    { label: "Sex", value: caseData.sex === "female" ? "Female" : "Male" },
  ];

  if (caseData.age_years !== null) {
    headerFacts.push({ label: "Age", value: `${caseData.age_years}` });
  }
  if (caseData.height_cm !== null) {
    headerFacts.push({ label: "Height", value: `${caseData.height_cm} cm` });
  }
  if (caseData.weight_kg !== null) {
    headerFacts.push({ label: "Weight", value: `${caseData.weight_kg} kg` });
  }

  headerFacts.push({ label: "Visits", value: `${caseDigest.visits.length}` });
  headerFacts.push({ label: "Level", value: AUDIENCE_PROFILE_LABELS[caseData.profile] });
  headerFacts.push({ label: "Answered in", value: SPOKEN_LANGUAGE_LABELS[caseData.language] });

  const evaluatedVisits = caseDigest.visits.filter((v) => v.score !== null);
  if (evaluatedVisits.length > 0) {
    const meanScore =
      evaluatedVisits.reduce((acc, curr) => acc + (curr.score ?? 0), 0) / evaluatedVisits.length;
    headerFacts.push({ label: "Average score", value: `${Math.round(meanScore)} / 100` });
  }

  const chronologicalUpdates = caseDigest.record_updates.map((upd) => ({
    visitNo: upd.visit_no,
    when: upd.created_at,
    body: upd.body,
  }));

  const recordedSymptoms = caseDigest.symptoms.map((symp) => ({
    when: symp.created_at,
    structure: symp.organ_label,
    symptom: symp.symptom,
    severity: symp.severity,
  }));

  const compiledVisits = caseDigest.visits.map((visit) => {
    const organLabels = visit.structures
      .map(labelFor)
      .filter((l): l is string => l !== null)
      .sort((a, b) => a.localeCompare(b));

    const transcriptMessages = (sessionDetailsMap.get(visit.session_id)?.messages ?? []).map((msg) => ({
      role: msg.role,
      body: stripOrganRefs(msg.content),
      when: msg.created_at,
      model: msg.model,
    }));

    return {
      visitNo: visit.visit_no,
      when: visit.created_at,
      score: visit.score,
      verdict: visit.verdict,
      structures: organLabels,
      exchanges: transcriptMessages,
    };
  });

  return {
    heading: caseData.title,
    kind: "case",
    facts: headerFacts,
    verdict: null,
    structures: [],
    notes: [],
    exchanges: [],
    findings: caseData.findings.trim() === "" ? null : caseData.findings,
    recordUpdates: chronologicalUpdates,
    symptoms: recordedSymptoms,
    visits: compiledVisits,
    sealedAnswer: caseDigest.ground_truth,
    language: caseData.language,
    createdAt: caseData.created_at,
    updatedAt: caseData.updated_at,
    producedAt,
  };
}

/**
 * Validates that document contains sufficient printable contents beyond headings.
 */
export function isPrintable(doc: PrintDocument): boolean {
  return (
    doc.notes.length > 0 ||
    doc.exchanges.length > 0 ||
    doc.visits.length > 0 ||
    doc.symptoms.length > 0 ||
    doc.recordUpdates.length > 0
  );
}
